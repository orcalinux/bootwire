#!/usr/bin/env python3
"""Finish the SVG files that PlantUML and Graphviz write, so every diagram looks the same everywhere.

    python3 svg_post.py FILE.svg ...

- paints a white background, so a diagram stays readable on a dark page (GitHub, VS Code, IDEs);
- gives every font a fallback list, so a viewer without Arial or DejaVu Sans Mono still gets a
  font with the same width (Helvetica, Liberation Sans, Menlo, Consolas ...);
- keeps the space at the start of a text piece (Graphviz splits text at every <b>);
- Graphviz only: sizes the image in px instead of pt, so its text has the same size as the
  text in the other diagrams.

Running it twice on the same file changes nothing.
"""
from __future__ import annotations

import html
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bootwire_figures import tw  # noqa: E402  Arial widths

SANS = "Arial, Helvetica, 'Liberation Sans', Arimo, sans-serif"
MONO = "'DejaVu Sans Mono', Menlo, Consolas, 'Liberation Mono', monospace"
FONTS = {
    "Arial": SANS,
    "DejaVu Sans Mono": MONO,
}
BG_ID = "bootwire-background"


TEXT = re.compile(r'<text\b([^>]*)>([^<]*)</text>')


def _attr(attrs: str, name: str) -> str | None:
    m = re.search(rf'\b{name}="([^"]*)"', attrs)
    return m.group(1) if m else None


def _respace_graphviz(svg: str) -> str:
    """Graphviz writes a line of mixed bold and normal text as one <text> per piece, each at an x
    it measured with hinted fonts. That adds up to 2 px after every bold word. Put each piece
    that continues a line right after the previous one, measured with the real Arial widths."""
    prev = None  # (y, x_end) of the last piece on the current line

    def place(m: re.Match) -> str:
        nonlocal prev
        attrs, content = m.group(1), m.group(2)
        x, y = _attr(attrs, "x"), _attr(attrs, "y")
        anchor = _attr(attrs, "text-anchor") or "start"
        size = float(_attr(attrs, "font-size") or 14)
        bold = _attr(attrs, "font-weight") == "bold"
        mono = "Mono" in (_attr(attrs, "font-family") or "")
        if x is None or y is None:
            prev = None
            return m.group(0)
        text = html.unescape(content)
        width = tw(text, size, bold, mono)
        xf = float(x)
        if anchor == "start" and prev and prev[0] == y and 0 <= xf - prev[1] <= 3.5:
            xf = prev[1]
            attrs = re.sub(r'\bx="[^"]*"', f'x="{xf:.2f}"', attrs, count=1)
        prev = (y, xf + width) if anchor == "start" else None
        return f"<text{attrs}>{content}</text>"

    return TEXT.sub(place, svg)


def fix(svg: str) -> str:
    if "Generated by graphviz" in svg:
        svg = _respace_graphviz(svg)
    for name, stack in FONTS.items():
        svg = svg.replace(f'font-family="{name}"', f'font-family="{stack}"')
    # Graphviz starts a text piece with the space that follows bold text; keep that space
    svg = re.sub(r"<text (?![^>]*xml:space)", '<text xml:space="preserve" ', svg)

    open_tag = re.search(r"<svg\b[^>]*>", svg)
    if not open_tag:
        raise ValueError("no <svg> element")
    tag = open_tag.group(0)

    # Graphviz: width="123pt" height="45pt" -> px, keep the viewBox
    new_tag = re.sub(r'(width|height)="([\d.]+)pt"', lambda m: f'{m.group(1)}="{float(m.group(2)):.0f}px"', tag)

    if f'id="{BG_ID}"' not in svg:
        vb = re.search(r'viewBox="([-\d.]+)[ ,]+([-\d.]+)[ ,]+([\d.]+)[ ,]+([\d.]+)"', new_tag)
        if vb:
            x, y, w, h = vb.groups()
            bg = f'<rect id="{BG_ID}" x="{x}" y="{y}" width="{w}" height="{h}" fill="#FFFFFF"/>'
        else:
            bg = f'<rect id="{BG_ID}" width="100%" height="100%" fill="#FFFFFF"/>'
        new_tag += bg
    return svg[:open_tag.start()] + new_tag + svg[open_tag.end():]


def main(paths: list[str]) -> int:
    for p in map(Path, paths):
        p.write_text(fix(p.read_text(encoding="utf-8")), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
